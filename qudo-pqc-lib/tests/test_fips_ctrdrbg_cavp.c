static void xor_buf(uint8_t *dst, const uint8_t *a, const uint8_t *b, size_t n)
{
    size_t i;
    for (i = 0; i < n; i++)
        dst[i] = a[i] ^ b[i];
}

static void print_diff(const uint8_t *got, const uint8_t *want, size_t n)
{
    size_t i, first = n;
    for (i = 0; i < n; i++) {
        if (got[i] != want[i]) {
            first = i;
            break;
        }
    }
    if (first == n) {
        printf("  (no byte differences)\n");
        return;
    }
    printf("  first mismatch at byte %zu\n", first);
    printf("  want[0..31]: ");
    for (i = 0; i < 32 && i < n; i++)
        printf("%02X", want[i]);
    printf("\n  got [0..31]: ");
    for (i = 0; i < 32 && i < n; i++)
        printf("%02X", got[i]);
    printf("\n");
}

int main(int argc, char **argv)
{
    test_fips_init_set_args(&argc, argv);
    qudo_pqc_ctrdrbg_ctx_t *ctx;
    uint8_t seed[48];
    uint8_t reseed_material[48];
    uint8_t discard[512];
    uint8_t output[512];
    int rc;

    printf("ACVP CTR_DRBG vector: tgId=15 tcId=211 (AES-256 no-df no-PR)\n");

    if (!test_fips_init()) {
        fprintf(stderr, "FAIL: qudo_pqc_init returned error\n");
        return 1;
    }

    ctx = qudo_pqc_ctrdrbg_new();
    if (ctx == NULL) {
        fprintf(stderr, "FAIL: ctrdrbg_new returned NULL\n");
        return 1;
    }

    xor_buf(seed, k_entropy, k_perso, 48);
    rc = qudo_pqc_ctrdrbg_init(ctx, 32, seed, 48);
    if (rc != 0) {
        fprintf(stderr, "FAIL: ctrdrbg_init rc=%d\n", rc);
        qudo_pqc_ctrdrbg_free(ctx);
        return 1;
    }

    xor_buf(reseed_material, k_reseed_entropy, k_reseed_addin, 48);
    rc = qudo_pqc_ctrdrbg_reseed(ctx, reseed_material, 48);
    if (rc != 0) {
        fprintf(stderr, "FAIL: ctrdrbg_reseed rc=%d\n", rc);
        qudo_pqc_ctrdrbg_free(ctx);
        return 1;
    }

    rc = qudo_pqc_ctrdrbg_generate(ctx, discard, sizeof(discard), k_gen1_addin,
                                   sizeof(k_gen1_addin));
    if (rc != 0) {
        fprintf(stderr, "FAIL: ctrdrbg_generate #1 rc=%d\n", rc);
        qudo_pqc_ctrdrbg_free(ctx);
        return 1;
    }

    rc = qudo_pqc_ctrdrbg_generate(ctx, output, sizeof(output), k_gen2_addin,
                                   sizeof(k_gen2_addin));
    if (rc != 0) {
        fprintf(stderr, "FAIL: ctrdrbg_generate #2 rc=%d\n", rc);
        qudo_pqc_ctrdrbg_free(ctx);
        return 1;
    }

    qudo_pqc_ctrdrbg_free(ctx);

    if (memcmp(output, k_expected, sizeof(k_expected)) != 0) {
        fprintf(stderr, "FAIL: returnedBits mismatch.\n");
        print_diff(output, k_expected, sizeof(k_expected));
        return 1;
    }

    printf("PASS: tg15/tc211 matched (512 bytes).\n");
    return 0;
}
